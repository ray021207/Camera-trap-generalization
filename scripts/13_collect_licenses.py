"""Phase 7: collect the licence of every pinned dependency, copy its licence files into
licenses/third_party/<package>/, and write results/licenses.json + THIRD_PARTY_LICENSES.md.

    python scripts/13_collect_licenses.py

Reads installed package metadata only (no network). Anything whose declared licence looks
copyleft / non-commercial is flagged so a human can look at it.
"""
import importlib.metadata as md
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.common import ROOT, save_json

FLAG = re.compile(r"GPL|AGPL|LGPL|NonCommercial|Non-Commercial|CC-BY-NC|SSPL|proprietary", re.I)


def declared_license(meta):
    expr = meta.get("License-Expression")
    if expr:
        return expr.strip()
    lic = (meta.get("License") or "").strip()
    if lic and len(lic) < 80 and "\n" not in lic:
        return lic
    cls = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if cls:
        return "; ".join(cls)
    return (lic[:60] + "...") if lic else "UNKNOWN (see licence file)"


def main():
    names = []
    for line in (ROOT / "requirements.txt").read_text().splitlines():
        line = line.strip()
        if line and not line.startswith(("-", "#")):
            names.append(re.split(r"[=<>]", line)[0])
    out_dir = ROOT / "licenses" / "third_party"
    shutil.rmtree(out_dir, ignore_errors=True)
    rows = []
    for n in sorted(names, key=str.lower):
        try:
            d = md.distribution(n)
        except md.PackageNotFoundError:
            rows.append(dict(package=n, version="?", license="NOT INSTALLED", files=[], flagged=False))
            continue
        meta = d.metadata
        lic = declared_license(meta)
        copied = []
        for f in d.files or []:
            nm = f.name.upper()
            if any(k in nm for k in ("LICENSE", "LICENCE", "COPYING", "NOTICE")) and "dist-info" in str(f):
                src = Path(d.locate_file(f))
                if src.is_file() and src.stat().st_size < 200_000:
                    dst = out_dir / n / src.name
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy(src, dst)
                    copied.append(src.name)
        rows.append(dict(package=n, version=meta["Version"], license=lic, files=copied, flagged=bool(FLAG.search(lic))))
    # dataset attribution facts straight from the CCT20 metadata (rights_holder field and info block)
    import collections, json
    holders, info = collections.Counter(), {}
    for n in ["train", "cis_val", "cis_test", "trans_val", "trans_test"]:
        f = ROOT / "data" / "meta" / "eccv_18_annotation_files" / f"{n}_annotations.json"
        if f.exists():
            j = json.load(open(f))
            holders.update(i["rights_holder"] for i in j["images"])
            info = j["info"]
    save_json(dict(dataset_rights_holders_image_counts=dict(holders), dataset_info_block=info, n_packages=len(rows), flagged=[r["package"] for r in rows if r["flagged"]],
                   no_licence_file_copied=[r["package"] for r in rows if not r["files"]], packages=rows), "licenses")
    md_lines = ["# Third-party software licences", "",
                "Generated by `scripts/13_collect_licenses.py` from the installed package metadata of every pinned dependency "
                "(`requirements.txt`). Licence files shipped by each package are copied to `licenses/third_party/<package>/`.", "",
                "| Package | Version | Declared licence | Licence file(s) copied |", "|---|---|---|---|"]
    for r in rows:
        md_lines.append(f"| {r['package']} | {r['version']} | {r['license']}{'  **(check)**' if r['flagged'] else ''} | {', '.join(r['files']) or 'none shipped'} |")
    (ROOT / "THIRD_PARTY_LICENSES.md").write_text("\n".join(md_lines) + "\n", encoding="utf-8")
    print(len(rows), "packages; flagged:", [r["package"] for r in rows if r["flagged"]],
          "| no licence file:", [r["package"] for r in rows if not r["files"]])


if __name__ == "__main__":
    main()
